int	ft_is_prime(int nb)
{
	int	n;

	if (nb <= 0)
		return (0);
	if (nb == 1)
		return (0);
	n = 2;
	while (n < nb)
	{
		if (nb % n == 0)
			return (0);
		n++;
	}
	return (1);
}

int main ()
{
	printf("%d", ft_is_prime(-5));
}