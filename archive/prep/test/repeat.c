int main (int argc, char **argv)
{
    int i;
    int rep;
    
    i = 0;
    
    if (argc == 2)
    {
        while (argv[1][i])
        {
            rep = (argv[1][i] | 32) - 'a' + 1;
            while(rep--)
            {
                write (1, &argv[1][i], 1);
                
                
            }
            i++;
        }
        
     
   }
   write(1, "\n", 1);
   
}
