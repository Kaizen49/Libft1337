char *strdup(const char *s1)
{
    int i;
    char *s2;
    
    i = 0;
    while (s1[i])
        i++;
    s2 = malloc (sizeof(char) * (i + 1));
    if (!s2)
        return (NULL);
    
    i = 0 ;
    while (s1[i])
    {
        s2[i] = s1[i];
        i++;
    }
    s2[i] = '\0';
    return  (s2);
}